#!/usr/bin/env python3
"""Sync Charmed's Sage Midnight bindings from a pinned lanej/dotfiles checkout."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import tomllib
import urllib.request


REVISION = "eda3659b1aec1fd3b51e4c17f36a62c2479a58df"
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "theme/sage_tokens_generated.go"


# Charmed consumes this subset of the shared design system. State roles resolve upstream.
ROLES = """
accent border diff.add diff.add.bg diff.add.emph.bg diff.delete diff.delete.bg
diff.delete.emph.bg file.executable focus git.file.ahead git.file.behind git.file.branch
git.file.conflicted git.file.deleted git.file.modified git.file.renamed git.file.staged
git.file.stashed git.file.typechanged git.file.untracked git.summary.added_lines
git.summary.branch git.summary.changed_files git.summary.removed_lines
git.summary.untracked_files heading keyhint link match selection.bg selection.fg
status.error status.info status.success status.warning surface surface.raised
syntax.boolean.false syntax.boolean.true syntax.comment syntax.constant syntax.function
syntax.keyword syntax.member syntax.null syntax.number syntax.operator syntax.receiver
syntax.section syntax.special syntax.string syntax.type syntax.variable
syntax.variable.reference tab.active.bg tab.active.fg tab.inactive.bg tab.inactive.fg
text text.inverse text.muted text.subtle
""".split()
STATES = """
access.readonly access.readwrite configuration.off configuration.on
connectivity.connected connectivity.disconnected data.fresh data.missing data.stale
execution.canceled execution.paused execution.queued execution.running health.unknown
interaction.disabled severity.debug severity.fatal severity.trace
""".split()
SWATCHES = """
amber blue copper cyan dusty_rose lavender lichen muted
""".split()
BOLD_STATES = ["severity.fatal"]


def identifier(prefix, name):
    return prefix + "".join(part.capitalize() for part in re.split(r"[._]", name))


def upstream(path, checkout):
    path = "design-system/" + path
    if checkout:
        return subprocess.check_output(["git", "-C", checkout, "show", f"{REVISION}:{path}"])
    url = f"https://raw.githubusercontent.com/lanej/dotfiles/{REVISION}/{path}"
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()


def render(colors, tokens, preset):
    if colors["theme"] != "sage" or tokens["theme"] != "sage" or preset["name"] != "sage":
        raise ValueError("expected Sage exports from the pinned dotfiles revision")

    roles = colors["roles"]
    selected_roles = set(ROLES)
    states = []
    for name in STATES:
        state = tokens["semantic_states"][name]
        role = state["color_role"].removeprefix("@")
        if roles[role] != state["fg"]:
            raise ValueError(f"{name} foreground disagrees with its {role} role")
        selected_roles.add(role)
        states.append(f'{identifier("state", name)} = {identifier("role", role)} // {name}')
    for name in BOLD_STATES:
        bold = tokens["semantic_states"][name]["bold"]
        if not isinstance(bold, bool):
            raise ValueError(f"invalid emphasis for {name}: {bold}")
        states.append(f'{identifier("state", name)}Bold = {str(bold).lower()} // {name}.bold')

    lines = [
        "// Code generated by scripts/sync_sage_tokens.py; DO NOT EDIT.",
        f"// Source: https://github.com/lanej/dotfiles/tree/{REVISION}/design-system",
        "package theme", "",
    ]
    for prefix, names, source in [("role", selected_roles, roles), ("swatch", SWATCHES, preset["palette"])]:
        lines.append("const (")
        for name in sorted(names):
            value = source[name]
            if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
                raise ValueError(f"invalid RGB value for {name}: {value}")
            lines.append(f'{identifier(prefix, name)} = "{value.lower()}" // {name}')
        lines.extend([")", ""])
    if states:
        lines.extend(["const (", *states, ")", ""])
    return subprocess.run(["gofmt"], input="\n".join(lines), text=True,
                          check=True, capture_output=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dotfiles", type=Path, help="read the pinned Git objects from this local checkout")
    parser.add_argument("--check", action="store_true", help="compare with the checked-in Go bindings")
    args = parser.parse_args()

    result = render(json.loads(upstream("generated/colors.json", args.dotfiles)),
                    json.loads(upstream("generated/tokens.json", args.dotfiles)),
                    tomllib.loads(upstream("themes/sage.toml", args.dotfiles).decode()))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            parser.exit(1, "Sage token bindings are stale. Run scripts/sync_sage_tokens.py.\n")
    else:
        OUTPUT.write_text(result)


if __name__ == "__main__":
    main()
